-- ARCHIVE 001 — initial Supabase schema
-- Apply once to a NEW, empty Supabase project.
-- Customer data is private by default. Do not add service_role keys to the frontend.

-- -----------------------------------------------------------------------------
-- 1. Private helper schema and owner check
-- -----------------------------------------------------------------------------
create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated;

-- -----------------------------------------------------------------------------
-- 2. Customer profiles
-- -----------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  full_name text,
  phone text,
  role text not null default 'customer' check (role in ('customer', 'owner')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function private.is_owner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = (select auth.uid())
      and p.role = 'owner'
  );
$$;

revoke all on function private.is_owner() from public, anon;
grant execute on function private.is_owner() to authenticated;

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, full_name)
  values (
    new.id,
    new.email,
    coalesce(
      nullif(new.raw_user_meta_data ->> 'full_name', ''),
      nullif(new.raw_user_meta_data ->> 'name', ''),
      split_part(coalesce(new.email, ''), '@', 1)
    )
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

revoke all on function public.handle_new_auth_user() from public, anon, authenticated;

create trigger on_auth_user_created_archive001
  after insert on auth.users
  for each row execute function public.handle_new_auth_user();

create or replace function public.sync_auth_user_email()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.profiles
  set email = new.email,
      updated_at = now()
  where id = new.id;
  return new;
end;
$$;

revoke all on function public.sync_auth_user_email() from public, anon, authenticated;

create trigger on_auth_user_email_changed_archive001
  after update of email on auth.users
  for each row
  when (old.email is distinct from new.email)
  execute function public.sync_auth_user_email();

-- -----------------------------------------------------------------------------
-- 3. Requests (one customer can have many independent requests)
-- -----------------------------------------------------------------------------
create table public.requests (
  id uuid primary key default gen_random_uuid(),
  request_number bigint generated by default as identity unique,
  request_code text generated always as ('REQ-' || lpad(request_number::text, 6, '0')) stored unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  contact_name text,
  contact_phone text not null,
  budget numeric(10,2) not null check (budget >= 0),
  categories text[] not null default '{}',
  clothing_sizes text,
  shoe_size text,
  preferred_brands text,
  reference_links text[] not null default '{}',
  customer_notes text,
  status text not null default 'received' check (status in (
    'received',
    'searching',
    'proposal_ready',
    'awaiting_approval',
    'approved',
    'purchasing',
    'arrived_inspection',
    'ready_to_ship',
    'shipped',
    'completed',
    'cancelled'
  )),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index requests_user_id_created_at_idx
  on public.requests (user_id, created_at desc);
create index requests_status_idx on public.requests (status);

-- -----------------------------------------------------------------------------
-- 4. Customer reference images (private Storage bucket)
