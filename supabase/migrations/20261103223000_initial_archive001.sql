create or replace function public.log_request_status_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.request_events (
      request_id, actor_id, event_type, new_status, message
    ) values (
      new.id, (select auth.uid()), 'request_created', new.status,
      'Solicitud recibida'
    );
  elsif old.status is distinct from new.status then
    insert into public.request_events (
      request_id, actor_id, event_type, previous_status, new_status, message
    ) values (
      new.id, (select auth.uid()), 'status_changed', old.status, new.status,
      'El estado de la solicitud ha cambiado'
    );
  end if;
  return new;
end;
$$;

revoke all on function public.log_request_status_change() from public, anon, authenticated;

create trigger requests_log_status_change
  after insert or update of status on public.requests
  for each row execute function public.log_request_status_change();

