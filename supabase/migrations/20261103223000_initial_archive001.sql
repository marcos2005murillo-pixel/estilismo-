insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('request-references', 'request-references', false, 5242880,
    array['image/jpeg', 'image/png', 'image/webp', 'image/heic']),
  ('selection-images', 'selection-images', false, 5242880,
    array['image/jpeg', 'image/png', 'image/webp', 'image/heic'])
on conflict (id) do update
set public = excluded.public,
    file_size_limit = excluded.file_size_limit,
    allowed_mime_types = excluded.allowed_mime_types;

-- Paths in request-references must start with <request-uuid>/filename.
create policy archive_reference_images_read
  on storage.objects for select to authenticated
  using (
    bucket_id = 'request-references'
    and (
      (select private.is_owner())
      or exists (
        select 1 from public.requests r
        where r.id::text = (storage.foldername(name))[1]
          and r.user_id = (select auth.uid())
      )
    )
  );

create policy archive_reference_images_upload
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'request-references'
    and exists (
      select 1 from public.requests r
      where r.id::text = (storage.foldername(name))[1]
        and r.user_id = (select auth.uid())
    )
  );

create policy archive_reference_images_delete
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'request-references'
    and (
      (select private.is_owner())
      or exists (
        select 1 from public.requests r
        where r.id::text = (storage.foldername(name))[1]
          and r.user_id = (select auth.uid())
      )
    )
  );

-- Paths in selection-images must start with <request-uuid>/<item-uuid>/filename.
create policy archive_selection_images_read
  on storage.objects for select to authenticated
  using (
    bucket_id = 'selection-images'
    and (
      (select private.is_owner())
      or exists (
        select 1
        from public.request_item_images img
        join public.requests r on r.id = img.request_id
        where img.storage_path = name
          and img.client_visible = true
          and r.user_id = (select auth.uid())
      )
    )
  );

create policy archive_selection_images_upload
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'selection-images'
