create index request_item_images_item_id_idx
  on public.request_item_images (item_id);

-- -----------------------------------------------------------------------------
-- 6. Costs (commission is calculated from the final number of items)
-- -----------------------------------------------------------------------------
create table public.request_costs (
  request_id uuid primary key references public.requests(id) on delete cascade,
  garments_total numeric(10,2) not null default 0 check (garments_total >= 0),
  purchase_shipping_total numeric(10,2) not null default 0 check (purchase_shipping_total >= 0),
  other_purchase_costs numeric(10,2) not null default 0 check (other_purchase_costs >= 0),
  commission_item_count smallint not null default 0 check (commission_item_count between 0 and 12),
  commission_amount numeric(10,2) generated always as (
    case
      when commission_item_count between 1 and 3 then 8.00
      when commission_item_count between 4 and 5 then 14.00
      when commission_item_count between 6 and 8 then 21.00
      when commission_item_count between 9 and 12 then 28.00
      else 0.00
    end
  ) stored,
  packaging_cost numeric(10,2) not null default 0 check (packaging_cost >= 0),
  final_shipping_cost numeric(10,2) not null default 0 check (final_shipping_cost >= 0),
  client_visible boolean not null default false,
  updated_at timestamptz not null default now()
);

create view public.request_cost_totals
with (security_invoker = true)
as
select
  request_id,
  garments_total,
  purchase_shipping_total,
  other_purchase_costs,
  commission_item_count,
  commission_amount,
  packaging_cost,
  final_shipping_cost,
  client_visible,
  updated_at,
  (garments_total + purchase_shipping_total + other_purchase_costs
    + commission_amount + packaging_cost + final_shipping_cost) as grand_total
from public.request_costs;

