create index request_reference_images_request_id_idx
  on public.request_reference_images (request_id);

-- -----------------------------------------------------------------------------
-- 5. Items found by the owner for a request
-- -----------------------------------------------------------------------------
create table public.request_items (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.requests(id) on delete cascade,
  title text not null,
  brand text,
  size text,
  condition text,
  item_price numeric(10,2) not null default 0 check (item_price >= 0),
  source_shipping numeric(10,2) not null default 0 check (source_shipping >= 0),
  source_url text,
  customer_description text,
  status text not null default 'proposed' check (status in (
    'proposed',
    'unavailable',
    'purchased',
    'received',
    'inspection_ok',
    'inspection_issue',
    'packed',
    'shipped',
    'cancelled'
  )),
  client_visible boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (id, request_id)
);

create index request_items_request_id_idx
  on public.request_items (request_id, sort_order);

-- Customers approve/reject an item without receiving permission to edit its price/details.
create table public.request_item_decisions (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null,
  item_id uuid not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  decision text not null check (decision in ('accepted', 'rejected')),
  customer_note text,
  decided_at timestamptz not null default now(),
  unique (item_id, user_id),
  foreign key (item_id, request_id)
    references public.request_items (id, request_id) on delete cascade
);

create index request_item_decisions_request_id_idx
  on public.request_item_decisions (request_id);

-- Photos of items selected by the owner. Actual files live in a private bucket.
create table public.request_item_images (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null,
  item_id uuid not null,
  storage_path text not null unique,
  original_filename text,
  content_type text,
  size_bytes bigint check (size_bytes is null or size_bytes >= 0),
